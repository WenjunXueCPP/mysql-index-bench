USE bench;

-- =============================================================
-- 场景：按状态过滤 + 按金额倒序取前 20 条
-- 典型业务："查看待处理订单中金额最高的 20 笔"
-- =============================================================

-- -------------------------------------------------------------
-- 步骤 1：优化前查询
-- 预期：20 rows in set (0.3s ~ 0.5s)
-- 注意：请记下这一行的时间，这是简历里要用的"优化前"数字
-- -------------------------------------------------------------
SELECT * FROM orders WHERE status = 3 ORDER BY amount DESC LIMIT 20;

-- -------------------------------------------------------------
-- 步骤 2：优化前执行计划
-- 预期：type = ALL，rows ≈ 1021815，Extra = Using where; Using filesort
-- 关键信号是 Using filesort —— 说明过滤完还要全量重排
-- -------------------------------------------------------------
EXPLAIN SELECT * FROM orders WHERE status = 3 ORDER BY amount DESC LIMIT 20;

-- -------------------------------------------------------------
-- 步骤 3：建立联合索引
-- 顺序：等值过滤列(status)在前，排序取前列(amount)在后
-- 预期：Query OK, 2-3 秒（1 核 2G 上建 102 万行索引）
-- -------------------------------------------------------------
ALTER TABLE orders ADD INDEX idx_status_amount (status, amount);

-- -------------------------------------------------------------
-- 步骤 4：优化后查询
-- 预期：20 rows in set (0.00s ~ 0.02s)
-- 返回的 20 行应当与步骤 1 完全一致 —— 顺序和数据都没变，只是更快
-- -------------------------------------------------------------
SELECT * FROM orders WHERE status = 3 ORDER BY amount DESC LIMIT 20;

-- -------------------------------------------------------------
-- 步骤 5：优化后执行计划
-- 预期：type = ref，key = idx_status_amount，Extra = Using where
-- 核心变化：Using filesort 消失
-- 说明：rows 仍可能是 40 万级，这是优化器对低基数列的估算，
--       不代表实际读取行数 —— 实际只读到前 20 行就停了
-- -------------------------------------------------------------
EXPLAIN SELECT * FROM orders WHERE status = 3 ORDER BY amount DESC LIMIT 20;


-- =============================================================
-- 附：对照实验（可选）
-- 把索引顺序反过来，验证"等值列在前、排序列在后"的必要性
-- =============================================================

-- 先删掉刚才的索引
ALTER TABLE orders DROP INDEX idx_status_amount;

-- 建一个顺序相反的索引：排序列在前，过滤列在后
ALTER TABLE orders ADD INDEX idx_amount_status (amount, status);

-- 同样一条查询，filesort 依然存在，索引基本没帮上忙
EXPLAIN SELECT * FROM orders WHERE status = 3 ORDER BY amount DESC LIMIT 20;

-- 清理
ALTER TABLE orders DROP INDEX idx_amount_status;


